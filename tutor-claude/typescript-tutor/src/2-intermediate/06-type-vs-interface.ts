/**
 * ============================================================================
 * 06. type vs interface — 무엇을 언제 쓰나
 * ============================================================================
 *
 * 둘 다 "타입에 이름을 붙이는" 도구입니다. 90%는 서로 바꿔 써도 됩니다.
 * 하지만 차이가 있고, 팀 컨벤션을 정할 때 근거가 됩니다.
 *
 * 실행:  npx tsx src/2-intermediate/06-type-vs-interface.ts
 * ============================================================================
 */

// ----------------------------------------------------------------------------
// 1) 객체 모양 정의 — 둘 다 가능
// ----------------------------------------------------------------------------
interface UserI {
  id: number;
  name: string;
}
type UserT = {
  id: number;
  name: string;
};

// ----------------------------------------------------------------------------
// 2) 확장 방법이 다르다
// ----------------------------------------------------------------------------
// interface → extends 키워드
interface AdminI extends UserI {
  role: string;
}
// type → 교차 타입(&)
type AdminT = UserT & {
  role: string;
};

// ----------------------------------------------------------------------------
// 3) interface 만 가능한 것: "선언 병합(declaration merging)"
// ----------------------------------------------------------------------------
// 같은 이름의 interface를 여러 번 선언하면 자동으로 합쳐진다.
interface Window2 {
  title: string;
}
interface Window2 {
  version: number;
}
// 이제 Window2 는 { title: string; version: number }
const w: Window2 = { title: 'main', version: 1 };

// → 라이브러리 타입을 "확장"할 때 유용 (예: Express의 Request에 user 추가).
//   반대로, 의도치 않은 병합이 버그가 될 수도 있어 앱 코드에선 조심.

// ----------------------------------------------------------------------------
// 4) type 만 가능한 것: 유니온 / 튜플 / 원시 별칭 / 매핑·조건부 타입
// ----------------------------------------------------------------------------
type Id = number | string;                 // 유니온 — interface로는 불가능
type Pair = [number, number];              // 튜플
type Nullable<T> = T | null;               // 유틸리티성 별칭
type Keys = keyof UserT;                    // 'id' | 'name'

// ----------------------------------------------------------------------------
// 5) 실무 가이드라인 (정답은 없지만 흔한 컨벤션)
// ----------------------------------------------------------------------------
//  - "객체/클래스의 공개 형태(shape), 특히 라이브러리 공개 API" → interface
//  - "유니온, 함수 시그니처, 유틸리티 타입, 조합이 복잡한 타입"   → type
//  - 한 팀 안에서는 "하나로 통일"하는 게 가장 중요
//  - 성능상 큰 차이 없음 (아주 큰 타입에서 interface가 캐싱에 유리하다는 정도)

// ----------------------------------------------------------------------------
// 6) 확장 예시를 실제로 사용
// ----------------------------------------------------------------------------
const admin1: AdminI = { id: 1, name: 'a', role: 'admin' };
const admin2: AdminT = { id: 2, name: 'b', role: 'superadmin' };

function toLabel(u: UserI | UserT): string {
  return `#${u.id} ${u.name}`;
}

console.log('--- 06. type vs interface ---');
console.log(toLabel(admin1), '/', toLabel(admin2));
console.log('merged interface w =', w);
const someId: Id = 'abc-123';
console.log('Id 유니온 값 =', someId);

export {};
