/**
 * ============================================================================
 * 01. 기본 타입 (Basic Types)
 * ============================================================================
 *
 * TypeScript = JavaScript + "타입(type)".
 * 타입은 "이 변수/값이 어떤 모양인지"를 미리 약속하는 것입니다.
 * 이 약속을 어기면 코드를 실행하기 전에(= 컴파일 타임에) 에러로 알려줍니다.
 *
 * 실행:  npx tsx src/1-basic/01-types.ts
 * ============================================================================
 */

// ----------------------------------------------------------------------------
// 1) 타입 표기(annotation): 콜론(:) 뒤에 타입을 적는다
// ----------------------------------------------------------------------------
const username: string = '홍길동';
const age: number = 30; // 정수/실수 구분 없이 모두 number
const isAdmin: boolean = false;

// 아래 줄의 주석을 풀면 컴파일 에러가 납니다.
// (string 자리에 number를 넣을 수 없음)
// const wrong: string = 123;

// ----------------------------------------------------------------------------
// 2) 타입 추론(inference): 대부분은 타입을 안 적어도 TS가 알아서 추론한다
// ----------------------------------------------------------------------------
// 아래 nickname의 타입은 자동으로 string 으로 추론됨. → 굳이 `: string`을 안 써도 됨.
const nickname = 'gildong';
let score = 100; // number 로 추론

// score = '높음'; // ❌ number 변수에 string 대입 불가

// 💡 실무 팁: 초기값이 있으면 타입 표기를 생략하는 편이 깔끔합니다.
//    함수의 "매개변수"와 "반환 타입", 그리고 "빈 값으로 시작하는 변수"에만 주로 표기합니다.

// ----------------------------------------------------------------------------
// 3) 특수 타입: any / unknown / never / void
// ----------------------------------------------------------------------------

// any: "타입 검사를 포기한다". 아무 값이나 들어오고 아무 조작이나 허용됨.
//      → 편하지만 TS를 쓰는 의미가 사라짐. 실무에서는 최대한 피한다.
let anything: any = 10;
anything = '문자열도 됨';
// anything.foo.bar;  // TS는 에러를 안 냄 → 런타임에 TypeError로 터짐. 위험!

// unknown: "타입을 아직 모른다". any처럼 아무 값이나 담을 수 있지만,
//          쓰기 전에 반드시 "타입을 좁혀야" 한다. → 안전한 any.
let value: unknown = '문자열일 수도, 숫자일 수도';
// value.toUpperCase();          // ❌ 아직 뭔지 모르므로 사용 불가
if (typeof value === 'string') {
  // 이 블록 안에서는 value가 string으로 좁혀짐
  console.log('대문자:', value.toUpperCase());
}

// void: "반환값이 없다"는 함수의 반환 타입
function logMessage(msg: string): void {
  console.log('[LOG]', msg);
}

// never: "절대 발생하지 않는다" = 값을 가질 수 없는 타입
//        항상 예외를 던지거나, 무한 루프인 함수의 반환 타입
function throwError(message: string): never {
  throw new Error(message);
}

// ----------------------------------------------------------------------------
// 4) null 과 undefined (strictNullChecks 켜져 있을 때)
// ----------------------------------------------------------------------------
// tsconfig의 strict가 켜져 있으면 null/undefined는 별도의 타입으로 취급됨.
let maybeName: string | null = null; // "string 또는 null"
maybeName = '이름 생김';

// let name2: string = null; // ❌ string 에 null 을 넣을 수 없음

// ----------------------------------------------------------------------------
// 5) 리터럴 타입: "특정 값 그 자체"를 타입으로 사용
// ----------------------------------------------------------------------------
let direction: 'up' | 'down' | 'left' | 'right';
direction = 'up';
// direction = 'top'; // ❌ 네 값 중 하나가 아님

// const 로 선언하면 타입이 더 좁게(리터럴로) 추론됨
const method = 'GET'; // 타입: 'GET'  (let 이었다면 string)

// ----------------------------------------------------------------------------
// 실행 결과 확인
// ----------------------------------------------------------------------------
console.log('--- 01. 기본 타입 ---');
console.log({ username, age, isAdmin, nickname, score, method, direction });
logMessage('logMessage 호출됨 (void 함수)');

export {}; // 이 파일을 "모듈"로 만들어 전역 스코프 오염을 막는 관용구
