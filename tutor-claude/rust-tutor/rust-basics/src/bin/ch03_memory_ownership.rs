// 이 챕터에서 배울 것
//   1. 스택(stack)과 힙(heap) — Java 에서는 신경 안 쓰던 것
//   2. GC 없이 메모리를 어떻게 정리하나? → 소유권(ownership) 3원칙
//   3. 이동(move): 대입하면 "복사"가 아니라 "소유권이 넘어감"
//   4. Copy 타입 vs 이동 타입
//   5. clone(): 명시적인 깊은 복사
//   6. drop: 스코프를 벗어나면 자동 정리 (RAII) → Mutex 잠금 자동 해제의 원리
//
// =============================================================================
// 🧠 먼저 그림으로 이해하기: Java 는 어떻게 메모리를 관리했나?
// =============================================================================
//
//   Java:
//     String a = new String("hello");
//     String b = a;              // 같은 객체를 가리키는 "참조"가 2개
//
//        스택               힙
//      ┌──────┐         ┌─────────┐
//      │ a  ●─┼────────▶│ "hello" │
//      │ b  ●─┼────────▶│         │ 
//      └──────┘         └─────────┘
//
//     → 누가 이 "hello"를 지워야 할까? Java 는 신경 쓰지 않아도 됩니다.
//       GC(가비지 컬렉터)가 주기적으로 돌면서 "아무도 안 가리키는 객체"를 찾아 지웁니다.
//       편하지만, GC 가 도는 동안 멈춤(Stop-the-world)이 생기고 메모리를 더 씁니다.
//
//   C/C++:
//     프로그래머가 직접 free()/delete 로 지움 → 깜빡하면 메모리 누수,
//     두 번 지우면 크래시(double free), 지운 걸 또 쓰면 보안 취약점(use-after-free).
//
//   Rust:
//     "각 값에는 주인(owner)이 딱 하나 있고, 주인이 사라질 때 값도 지운다"는 규칙을
//     **컴파일러가 컴파일 시점에 검사**합니다. → GC 도 없고, 직접 free 도 안 하는데 안전!
//     대신 우리가 그 규칙을 지키며 코드를 써야 합니다. 이게 Rust 가 어렵게 느껴지는 이유입니다.
//
// =============================================================================
// 🧠 스택 vs 힙
// =============================================================================
//
//   스택(stack): 함수가 호출될 때 생기고, 함수가 끝나면 통째로 사라지는 메모리.
//               매우 빠름. 대신 "크기를 컴파일 시점에 알 수 있는" 값만 놓을 수 있음.
//               예) i32, u64, bool, char, (i32, f64) 튜플, [i32; 3] 배열
//
//   힙(heap)   : 크기가 실행 중에 바뀔 수 있는 데이터를 놓는 곳. 직접 할당/해제가 필요.
//               예) String 의 글자들, Vec 의 원소들, HashMap 의 데이터
//
//   Rust 의 String 은 실제로 이렇게 생겼습니다:
//
//        스택 (String 본체, 24바이트)        힙 (실제 글자)
//      ┌────────────────────┐          ┌───┬───┬───┬───┬───┐
//      │ ptr       ●────────┼─────────▶│ h │ e │ l │ l │ o │
//      │ len       5        │          └───┴───┴───┴───┴───┘
//      │ capacity  5        │
//      └────────────────────┘
//
//   Java 에서는 int 같은 원시 타입만 스택에 있고, 객체는 전부 힙에 있었죠.
//   Rust 는 구조체도 기본적으로 스택에 놓입니다(필드 중 String 같은 것이 힙을 가리킬 뿐).
