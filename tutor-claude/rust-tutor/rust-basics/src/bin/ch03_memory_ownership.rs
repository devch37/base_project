//   into_xxx(self)    자기 자신을 소비해서 변환하는 메서드 관례
//   스코프 끝 = drop  메모리 해제, 파일 닫기, 잠금 해제가 자동 (RAII)
//
// 💬 Java 개발자 관점 요약
//   Java 의 "모든 객체 변수 = 참조, GC 가 정리" 라는 감각을 버리고,
//   "모든 값에는 주인이 하나, 넘기면 주인이 바뀜, 주인이 사라지면 같이 사라짐" 으로 바꿔 생각하세요.
