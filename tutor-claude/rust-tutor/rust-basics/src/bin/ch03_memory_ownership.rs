// -----------------------------------------------------------------------------
// 1. 소유권 3원칙
// -----------------------------------------------------------------------------
//   ① 모든 값에는 주인(owner)인 변수가 하나 있다.
//   ② 주인은 한 번에 딱 하나뿐이다.
//   ③ 주인이 스코프(자기가 선언된 { } 블록)를 벗어나면, 값은 자동으로 정리(drop)된다.
fn ownership_rules() {
    println!("--- 1. 소유권 3원칙 ---");

    {
        // s 는 아직 없음
        let s = String::from("hello"); // s 가 "hello" 의 주인이 됨 (힙에 메모리 할당)
        println!("블록 안: {}", s);
    } // ← 블록 끝: 주인 s 가 사라짐 → Rust 가 자동으로 힙 메모리 해제 (drop 호출)
      //   컴파일러가 이 위치에 "메모리 해제 코드"를 알아서 넣어줍니다. GC 가 필요 없는 이유!

    // println!("{}", s); // ❌ s 는 이미 스코프 밖. 컴파일 에러
    println!();
}

// -----------------------------------------------------------------------------
// 2. 이동(Move) — Java 개발자가 가장 많이 부딪히는 지점
// -----------------------------------------------------------------------------
fn move_semantics() {
    println!("--- 2. 이동(move) ---");

    let a = String::from("hello");
    let b = a; // ⚠️ Java 라면 "참조 복사"지만, Rust 에서는 "소유권 이동"

    //   이동 후 메모리 모습:
    //
    //      a (무효)   ✗
    //      b  [ptr ●──┼──▶ "hello"]     ← 주인은 이제 b 하나뿐 (원칙 ②)
    //
    //   만약 a 와 b 둘 다 주인이라면? 둘 다 스코프를 벗어날 때 같은 메모리를 두 번 해제(double free)!
    //   그래서 Rust 는 대입 순간 a 를 "사용 불가" 상태로 만듭니다.

    // println!("{}", a);
    // ❌ error[E0382]: borrow of moved value: `a`
    //    value moved here: let b = a;
    //    help: consider cloning the value: let b = a.clone();

    println!("b = {}", b);

    // 이동은 이런 곳에서도 일어납니다:
    //   - 함수 인자로 넘길 때          take(s)        → 아래 5번 참고
    //   - 함수에서 반환할 때           return s
    //   - 구조체 필드에 넣을 때        Todo { title: s, ... }
    //   - Vec 에 push 할 때            v.push(s)
    //
    // 📌 actix 05_state 의 create_todo:
    //     let todo = Todo { id, title: body.into_inner().title, completed: false };
    //     todos.insert(id, todo.clone());   ← todo 를 HashMap 에 "이동"시키면
    //     HttpResponse::Created().json(todo) ← 여기서 todo 를 못 씀!
    //   그래서 insert 할 때 clone() 으로 복사본을 넣고, 원본은 응답에 사용한 것입니다.
    println!();
}

// -----------------------------------------------------------------------------
// 3. Copy 타입 — 이동 대신 복사되는 타입들
// -----------------------------------------------------------------------------
fn copy_types() {
    println!("--- 3. Copy 타입 ---");

    let x = 5;
    let y = x; // i32 는 Copy 타입 → 값이 그대로 복사됨. x 도 계속 사용 가능
    println!("x = {}, y = {}", x, y); // ✅ 문제없음

    // 왜? i32 는 스택에만 있는 4바이트짜리 값이라 복사가 아주 싸고,
    // 힙 메모리를 가리키지 않으니 double free 걱정도 없기 때문입니다.
    //
    // Copy 타입들 (Java 의 primitive 와 거의 같은 감각):
    //   정수(i32, u64...), 실수(f64), bool, char, &T(공유 참조),
    //   그리고 Copy 타입으로만 이뤄진 튜플/배열 (i32, bool), [u8; 4]
    //
    // Copy 가 아닌 타입 (= 대입하면 이동):
    //   String, Vec<T>, HashMap, Box<T> ... 힙을 소유하는 모든 것
    //   그리고 이것들을 필드로 가진 구조체

    // 📌 actix 05_state:  let id = *next_id;   → u64 는 Copy 라서 값만 복사해 올 수 있음
    println!();
}

// -----------------------------------------------------------------------------
// 4. clone() — 명시적인 깊은 복사
// -----------------------------------------------------------------------------
fn clone_example() {
    println!("--- 4. clone() ---");

    let a = String::from("hello");
    let b = a.clone(); // 힙 데이터까지 통째로 새로 복사 → 주인이 각각 하나씩
    println!("a = {}, b = {}", a, b); // ✅ 둘 다 사용 가능

    //      a [ptr ●─┼─▶ "hello"]
    //      b [ptr ●─┼─▶ "hello"]   ← 별개의 메모리
    //
    // clone() 은 비용이 드는 작업이라 Rust 는 "자동으로" 하지 않고 코드에 드러나게 합니다.
    // 코드에서 .clone() 이 보이면 "아, 여기서 복사 비용이 드는구나"를 알 수 있죠.
    //
    // 단, 예외적으로 "싼 clone" 도 있습니다:
    //   Arc::clone / Rc::clone → 데이터 복사 없이 참조 카운트만 +1 (ch11)
    //   📌 actix 05_state:  .app_data(state.clone())  ← state 는 web::Data(내부가 Arc) 라서 싸다!
    println!();
}

